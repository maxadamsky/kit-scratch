#!/usr/bin/env node
'use strict';

// Consumer: the operator, after Gate 2 and before scorer validation.

const fs = require('node:fs');
const path = require('node:path');

const {
  ARMS,
  BASE_MD5,
  buildAllFixtures,
  digest,
  normalizeFixture,
} = require('./generator.js');

const OUTPUT_PATH = path.join(__dirname, 'answer-key.json');
const BASE_HEAD = '6d4220647e6fccd2b3d6fd63179012a53ac69be3';
const PLACEHOLDER = '<READ-EVENT>:';

function normalizedBytes(fixture) {
  return normalizeFixture(fixture.bytes, fixture.arm).bytes;
}

function main() {
  const fixtures = buildAllFixtures();
  const reference = fixtures.get('A');
  const normalized = normalizedBytes(reference);

  for (const arm of ARMS) {
    const fixture = fixtures.get(arm.id);
    if (!normalized.equals(normalizedBytes(fixture))) {
      throw new Error(`normalized fixture ${arm.id} differs while building answer key`);
    }
    const projection = fixture.rows.map(({ id, state, date }) => ({ id, state, date }));
    const referenceProjection = reference.rows.map(({ id, state, date }) => ({ id, state, date }));
    if (JSON.stringify(projection) !== JSON.stringify(referenceProjection)) {
      throw new Error(`state/date projection differs in arm ${arm.id}`);
    }
  }

  const answerKey = {
    schemaVersion: 1,
    _meta: {
      consumers: ['runner.js', 'scorer.js'],
      generatedBy: 'build-answer-key.js',
    },
    base: {
      path: '.ai-delivery/conventions.md',
      md5: BASE_MD5,
      head: BASE_HEAD,
    },
    cursorResolution: {
      familyIndexBase: 0,
      controlCycle: ['ungrounded', 'unreachable', 'bare'],
      controlSwaps: reference.swaps,
      oldDateCursor: 'shared by old-grounded and unreachable rows in file order',
      recentDateCursor: 'recent-grounded rows in file order',
    },
    fixtures: Object.fromEntries(
      ARMS.map((arm) => {
        const fixture = fixtures.get(arm.id);
        return [
          arm.id,
          {
            token: arm.token,
            path: `fixtures/${arm.file}`,
            bytes: fixture.bytes.length,
            sha256: digest('sha256', fixture.bytes),
          },
        ];
      }),
    ),
    normalizedFixture: {
      placeholder: PLACEHOLDER,
      bytes: normalized.length,
      sha256: digest('sha256', normalized),
    },
    stateCounts: reference.stateCounts,
    lines: reference.rows.map((row) => ({
      id: row.id,
      family:
        row.index % 3 === 0
          ? 'old-grounded'
          : row.index % 3 === 1
            ? 'recent-grounded'
            : 'control',
      state: row.state,
      date: row.date,
      baseSource: row.source,
      baseTier: row.tier,
      fixtureSource: row.state === 'ungrounded' ? 'none' : row.state === 'bare' ? null : row.source,
      fixtureTier: row.state === 'ungrounded' ? '3-model' : row.state === 'bare' ? null : row.tier,
      objectivePile:
        row.state === 'ungrounded'
          ? 'Never-grounded'
          : row.state === 'bare'
            ? 'Human-authored'
            : null,
    })),
  };

  const generatedBytes = Buffer.from(`${JSON.stringify(answerKey, null, 2)}\n`, 'utf8');
  const command = process.argv[2];
  if (command === '--write') {
    fs.writeFileSync(OUTPUT_PATH, generatedBytes);
    console.log(
      `answer-key-written path=${OUTPUT_PATH} lines=${answerKey.lines.length} ` +
        `bytes=${generatedBytes.length} sha256=${digest('sha256', generatedBytes)}`,
    );
    return;
  }
  if (command === '--check') {
    const storedBytes = fs.readFileSync(OUTPUT_PATH);
    const equal = storedBytes.equals(generatedBytes);
    console.log(
      `answer-key-check byte-identical=${equal} lines=${answerKey.lines.length} ` +
        `bytes=${storedBytes.length} sha256=${digest('sha256', storedBytes)}`,
    );
    if (!equal) throw new Error('stored answer key differs from regenerated bytes');
    const mutated = Buffer.from(storedBytes);
    mutated[0] ^= 1;
    const mutationLanded = mutated[0] !== storedBytes[0];
    const controlEqual = mutated.equals(generatedBytes);
    console.log(
      `answer-key-check-control mutation_landed=${mutationLanded} ` +
        `byte-identical=${controlEqual}`,
    );
    if (!mutationLanded || controlEqual) {
      throw new Error('answer-key check control did not discriminate');
    }
    console.log('answer-key-check PASS');
    return;
  }
  throw new Error('usage: node build-answer-key.js --write|--check');
}

try {
  main();
} catch (error) {
  console.error(`answer-key-build FAIL: ${error.message}`);
  process.exitCode = 1;
}
